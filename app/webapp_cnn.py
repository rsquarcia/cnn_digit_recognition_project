# Pre-processiamo l'immagine disegnata per renderla simile ad una del dataset MNIST
# sul quale il modello è stato addestrato

def preprocess(pil_png):
    img = Image.alpha_composite(
            Image.new("RGBA", pil_png.size, (255,255,255,255)),
            pil_png.convert("RGBA")).convert("L")
    img = ImageOps.invert(img)

    arr = np.array(img)
    ys, xs = np.where(arr > 30)
    if ys.size == 0:
        raise ValueError("Il riquadro è vuoto.")

    top, bot = max(ys.min()-2,0), min(ys.max()+3, arr.shape[0])
    left, right = max(xs.min()-2,0), min(xs.max()+3, arr.shape[1])
    img = Image.fromarray(arr[top:bot, left:right])

    w, h = img.size
    scale = 20.0 / max(w, h)
    img = img.resize((int(round(w*scale)), int(round(h*scale))), Image.LANCZOS)

    canvas = Image.new("L",(28,28),0)
    canvas.paste(img, ((28-img.width)//2,(28-img.height)//2))
    arr = np.asarray(canvas, dtype="uint8")

    if (arr>0).mean() > 0.18:
        arr = ndi.binary_erosion(arr>0, iterations=1).astype("uint8")*255

    cy, cx = ndi.center_of_mass(arr)
    arr = ndi.shift(arr.astype("float32"), shift=(14-cy,14-cx),
                    order=0, mode="constant", cval=0)

    return (arr/255.0).reshape(1,28,28,1).astype("float32")

app = Flask(__name__)

